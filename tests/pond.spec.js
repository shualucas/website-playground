import { test, expect } from '@playwright/test';
test('pond responds to interaction, controls, and keyboard',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/pond.html');
  await expect(page.getByRole('heading',{name:'Stay a little. The world can wait.'})).toBeVisible();
  const pond=page.locator('canvas');
  await pond.click({position:{x:400,y:180}});
  await expect(page.locator('#activity')).toContainText('hello');
  await page.getByTitle('Switch between day and night').click();
  await expect(page.locator('html')).toHaveClass('night');
  await expect(page.locator('#weather')).toContainText('moon');
  await page.getByTitle('Pause animation (Space)').click();
  await expect(page.locator('#pause-label')).toHaveText('resume');
  await pond.focus();await page.keyboard.press('Space');
  await expect(page.locator('#pause-label')).toHaveText('pause');
  await page.getByTitle('Toggle pond sounds').click();
  await expect(page.locator('#sound-button')).toHaveAttribute('aria-pressed','true');
  await page.getByTitle('Toggle pond sounds').click();
  await expect(page.locator('#sound-button')).toHaveAttribute('aria-pressed','false');
  await page.getByRole('button',{name:'what is this?'}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await page.getByTitle('Switch between day and night').click();
  await page.screenshot({path:'/tmp/little-pond-desktop.png',fullPage:true});
  expect(errors).toEqual([]);
});
test('mobile fits and supports touch',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/pond.html');
  await expect(page.locator('canvas')).toBeVisible();
  await page.locator('canvas').click({position:{x:170,y:170}});
  await expect(page.locator('#activity')).toContainText('hello');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390);
  await page.screenshot({path:'/tmp/little-pond-mobile.png',fullPage:true});
});
test('reduced motion starts paused',async({page})=>{
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('/pond.html');
  await expect(page.locator('#pause-label')).toHaveText('resume');
});
