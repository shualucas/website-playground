import { test, expect } from '@playwright/test';
test('landing page animation, case study chapters, about, and sound controls',async({page})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'A little imagination. A lot of intention.'})).toBeVisible();
  const canvas=page.locator('canvas');
  await expect(canvas).toBeVisible();
  const before=await canvas.evaluate(c=>c.toDataURL());
  await expect.poll(()=>canvas.evaluate(c=>c.toDataURL())).not.toBe(before);
  const pause=page.getByRole('button',{name:'Pause dragon animation'});
  await pause.click();await expect(pause).toHaveAttribute('aria-pressed','true');
  const stopped=await canvas.evaluate(c=>c.toDataURL());
  await page.waitForTimeout(150);
  expect(await canvas.evaluate(c=>c.toDataURL())).toBe(stopped);
  await page.locator('body').click({position:{x:10,y:10}});
  await page.keyboard.press('Space');await expect(pause).toHaveAttribute('aria-pressed','false');
  await page.getByRole('link',{name:'Explore my work'}).click();
  await page.getByRole('button',{name:/Explore case study 01/}).click();
  const dialog=page.getByRole('dialog');
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole('heading',{name:'A clearer path forward.'})).toBeVisible();
  await dialog.getByRole('button',{name:/The discovery/}).click();
  await expect(dialog.getByRole('heading',{name:'What changed your understanding?'})).toBeVisible();
  await dialog.getByRole('button',{name:/Next chapter/}).click();
  await expect(dialog.getByRole('heading',{name:'What did you choose, and why?'})).toBeVisible();
  await page.keyboard.press('Escape');await expect(dialog).not.toBeVisible();
  await page.getByRole('button',{name:'A little about me',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Curious by nature. Designer by choice.'})).toBeVisible();
  await page.getByRole('button',{name:'Close about'}).click();
  const sound=page.getByRole('button',{name:'Toggle ambient sound'});
  await sound.click();await expect(sound).toHaveAttribute('aria-pressed','true');
  await sound.click();await expect(sound).toHaveAttribute('aria-pressed','false');
  expect(errors).toEqual([]);
});
test('mobile navigation, project dialogs and no overflow',async({page})=>{
  await page.setViewportSize({width:390,height:844});await page.goto('/');
  await page.getByRole('button',{name:'Menu +'}).click();
  await expect(page.locator('#main-nav')).toBeVisible();
  await page.getByRole('link',{name:'Selected work',exact:true}).click();
  await expect(page.locator('#main-nav')).not.toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390);
  await page.getByRole('button',{name:/Explore case study 03/}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('dialog').getByRole('heading',{name:'Built around the player.'})).toBeVisible();
  await page.getByRole('button',{name:'Close case study'}).click();
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:'/tmp/fantasy-mobile.png',fullPage:true});
});
